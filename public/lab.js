import { buildProposalSnapshots } from './core/proposal.js';
import { buildGateReport } from './core/gate.js';

const $ = id => document.getElementById(id);
let lab;
let configs;

async function readJson(path) {
  const response = await fetch(new URL(path, import.meta.url));
  if (!response.ok) throw new Error(`Could not load ${path}`);
  return response.json();
}

function render(proposal, provenance = 'human') {
  const snapshots = buildProposalSnapshots(lab, configs, proposal);
  const report = buildGateReport(snapshots, provenance);
  $('lab-decision').textContent = report.decision;
  $('lab-decision').className = report.decision === 'BLOCK' ? 'lab-block' : 'lab-review';
  $('lab-summary').textContent = `${report.summary} Human approval required.`;
  $('lab-diff').textContent = proposal.operations.map(operation =>
    `${operation.node}.conf\n+ ip route ${operation.prefix} ${operation.gateway} ${operation.distance}`)
    .join('\n\n');
  const findings = $('lab-findings');
  findings.replaceChildren();
  for (const intent of report.intents) {
    const row = document.createElement('div');
    row.className = intent.candidatePass ? 'finding-pass' : 'finding-fail';
    row.textContent = `${intent.id} · ${intent.candidateStatus} · ${intent.path.join(' → ')}${intent.returnStatus ? ` | return ${intent.returnStatus}: ${intent.returnPath.join(' → ')}` : ''}`;
    findings.append(row);
  }
  return report;
}

function error(message) {
  $('lab-decision').textContent = 'INVALID';
  $('lab-decision').className = 'lab-block';
  $('lab-summary').textContent = message;
  $('lab-diff').textContent = 'The proposal was not evaluated.';
  $('lab-findings').replaceChildren();
}

async function loadPreset(name) {
  try {
    const proposal = await readJson(`./labs/frr/proposals/${name}.json`);
    $('lab-proposal').value = JSON.stringify(proposal, null, 2);
    render(proposal);
  } catch (cause) { error(cause.message); }
}

$('lab-load-unsafe').addEventListener('click', () => loadPreset('route-leak'));
$('lab-load-safe').addEventListener('click', () => loadPreset('safe-reroute'));
$('lab-run').addEventListener('click', () => {
  try { render(JSON.parse($('lab-proposal').value)); }
  catch (cause) { error(cause.message); }
});

$('lab-ai-button').addEventListener('click', async () => {
  const button = $('lab-ai-button');
  button.disabled = true;
  $('lab-summary').textContent = 'Requesting a structured route proposal…';
  try {
    const response = await fetch(new URL('./api/ai/propose', document.baseURI), {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ request: $('lab-ai-request').value })
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || `HTTP ${response.status}`);
    $('lab-proposal').value = JSON.stringify(data.proposal, null, 2);
    const localReport = render(data.proposal, 'ai');
    if (localReport.decision !== data.report.decision || JSON.stringify(localReport.regressions) !== JSON.stringify(data.report.regressions)) {
      throw new Error('Server and browser safety gates disagree');
    }
    $('lab-summary').textContent += ` Proposal generated by ${data.model}; verify the route and intent paths before any use.`;
  } catch (cause) {
    $('lab-summary').textContent = `${cause.message}. Live AI needs the optional server and OPENAI_API_KEY; the local gate above remains available.`;
  } finally { button.disabled = false; }
});

try {
  lab = await readJson('./labs/frr/lab.json');
  configs = Object.fromEntries(await Promise.all(lab.nodes.map(async node => {
    const response = await fetch(new URL(`./labs/frr/baseline/${node.id}.conf`, import.meta.url));
    if (!response.ok) throw new Error(`Could not load ${node.id}.conf`);
    return [node.id, await response.text()];
  })));
  await loadPreset('route-leak');
} catch (cause) { error(cause.message); }
